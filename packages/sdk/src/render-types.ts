import type { FlagDefinition, FlagKind } from "@weathervane/core";

const TYPE_OF_KIND: Record<FlagKind, string> = {
  boolean: "boolean",
  string: "string",
  number: "number",
  json: "JsonValue",
};

/**
 * A declaration that fills in `FlagTypes`. Kinds map to plain types, not unions of the current
 * variations: a variation added after generation must still type-check where the flag is read.
 */
export function renderTypes(version: number, flags: readonly Pick<FlagDefinition, "key" | "kind">[]): string {
  const members = [...flags]
    .sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0))
    .map((flag) => `    ${JSON.stringify(flag.key)}: ${TYPE_OF_KIND[flag.kind]};`);
  return [
    `// Generated by weathervane-typegen from environment version ${version}. Do not edit by hand.`,
    `import type { JsonValue } from "@weathervane/node";`,
    ``,
    `declare module "@weathervane/node" {`,
    `  interface FlagTypes {`,
    ...members,
    `  }`,
    `}`,
    ``,
  ].join("\n");
}
