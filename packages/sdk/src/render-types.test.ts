import { describe, expect, it } from "vitest";
import { renderTypes } from "./render-types.ts";

describe("renderTypes", () => {
  it("declares one member per flag, sorted, with the type of its kind", () => {
    expect(
      renderTypes(12, [
        { key: "new-checkout", kind: "boolean" },
        { key: "banner", kind: "string" },
        { key: "limits", kind: "json" },
        { key: "max-items", kind: "number" },
      ]),
    ).toBe(`// Generated by weathervane-typegen from environment version 12. Do not edit by hand.
import type { JsonValue } from "@weathervane/node";

declare module "@weathervane/node" {
  interface FlagTypes {
    "banner": string;
    "limits": JsonValue;
    "max-items": number;
    "new-checkout": boolean;
  }
}
`);
  });
});
